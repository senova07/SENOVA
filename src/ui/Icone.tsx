export type NomIcone = keyof typeof ICONES

interface IconeProps {
  nom: NomIcone
  taille?: number
  /** `regular` (trait seul) partout ; `fill` pour les icônes vives, `bold` pour le ⋮. Jamais de duotone. */
  poids?: 'regular' | 'fill' | 'bold'
  className?: string
}

/** Icône Phosphor : trait simple d'une seule couleur, sans fond ni cadre. */
export function Icone({ nom, taille = 20, poids = 'regular', className }: IconeProps) {
  const Composant = ICONES[nom]
  return (
    <Composant
      size={taille}
      weight={poids}
      className={className}
      aria-hidden="true"
      data-poids={poids}
    />
  )
}
